public static class MainClass
{
    /*
    firstScore is the first score
    secondScore is the second score
    GetTotalScore adds the first and second scores together.
    Returns the total of the first and second scores.
*/

    public static int GetTotalScore(int firstScore, int secondScore)
    {
        return firstScore + secondScore;
    }
}